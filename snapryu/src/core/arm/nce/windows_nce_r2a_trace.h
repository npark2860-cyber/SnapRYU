// R2b-B2x1/B2x2: per-step recovery counter by WindowsPatchRecoveryKind value
// (0 substitution, 1 bitfield, 2 MRS TPIDR, 3 x18 conditional branch).
inline std::atomic<u64>& RecoveredStep(std::size_t kind, std::size_t step) noexcept {
    auto& g = G();
    switch (kind) {
    case 1:
        return g.recovered_bitfield_by_step[(std::min)(step, std::size_t{7})];
    case 2:
        return g.recovered_mrs_by_step[(std::min)(step, std::size_t{2})];
    case 3:
        return g.recovered_condbranch_by_step[(std::min)(step, std::size_t{8})];
    default:
        return g.recovered_by_step[(std::min)(step, RecoverySteps - 1)];
    }
}

// R2b-B2r3: what the X18-requesting capture reported as x18 on a recipe hit.
inline void NoteRecoveryX18(u64 x18, std::uintptr_t teb) noexcept {
    const std::size_t k = x18 == teb ? 0 : x18 == 0 ? 1 : 2;
    G().recovery_x18[k].fetch_add(1, std::memory_order_relaxed);
}

// Called by a break worker after it has released its job (no target suspended, no ArmNce held).
inline void MaybeFlush(bool force = false) noexcept {
    auto& g = G();
    constexpr u64 Interval = 5'000'000'000ULL;
    const u64 now = NowNs();
    u64 due = g.next_flush_ns.load(std::memory_order_relaxed);
    if (!force && (g.jobs.load(std::memory_order_relaxed) == 0 || now < due)) {
        return;
    }
    if (!force && !g.next_flush_ns.compare_exchange_strong(due, now + Interval,
                                                           std::memory_order_relaxed)) {
        return;
    }
    bool expected = false;
    if (!g.flushing.compare_exchange_strong(expected, true, std::memory_order_acquire)) {
        return;
    }
    try {
        Detail::WriteAll(force);
    } catch (...) {
    }
    g.flushing.store(false, std::memory_order_release);
}

