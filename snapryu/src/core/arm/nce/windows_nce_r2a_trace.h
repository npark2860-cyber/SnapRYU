// R2a delivery measurements (SNAPRYU_DIAGNOSTICS only). Observes the R1 cross-thread break
// delivery without changing it: where a target is when a capture is refused, how long a request
// waits, and what each capture costs. Nothing here feeds back into delivery decisions.
//
// Writers: SignalInterrupt (under PhysicalCore's guard), the per-core break workers, and the
// target core's host code (phase markers only). Results are written by a break worker after it
// has released its job, every few seconds and once more at process exit, to nce-r2a\ next to the
// executable. No logging, allocation or file I/O happens while a target is suspended.

