inline std::wstring OutputDir() {
    wchar_t path[MAX_PATH]{};
    const DWORD n = GetModuleFileNameW(nullptr, path, MAX_PATH);
    std::wstring dir(path, n);
    const auto slash = dir.find_last_of(L"\\/");
    dir = slash == std::wstring::npos ? L"." : dir.substr(0, slash);
    dir += L"\\nce-r2a";
    CreateDirectoryW(dir.c_str(), nullptr);
    return dir;
}

inline std::FILE* OpenTemp(const std::wstring& dir, const wchar_t* name, std::wstring& tmp) {
    tmp = dir + L"\\" + name + L".tmp";
    return _wfopen(tmp.c_str(), L"wb");
}

inline void Commit(std::FILE* f, const std::wstring& dir, const wchar_t* name,
                   const std::wstring& tmp) {
    std::fclose(f);
    const std::wstring final_path = dir + L"\\" + name;
    MoveFileExW(tmp.c_str(), final_path.c_str(), MOVEFILE_REPLACE_EXISTING);
}

inline void WriteHistogram(std::FILE* f, const char* name, const Histogram& h, bool comma) {
    const u64 n = h.count.load(std::memory_order_relaxed);
    std::fprintf(f,
                 "    \"%s\": {\"count\": %llu, \"mean_ns\": %llu, \"p50_le_ns\": %llu, "
                 "\"p90_le_ns\": %llu, \"p95_le_ns\": %llu, \"p99_le_ns\": %llu, \"max_ns\": %llu}%s\n",
                 name, static_cast<unsigned long long>(n),
                 static_cast<unsigned long long>(n ? h.sum.load(std::memory_order_relaxed) / n : 0),
                 static_cast<unsigned long long>(h.Quantile(0.50)),
                 static_cast<unsigned long long>(h.Quantile(0.90)),
                 static_cast<unsigned long long>(h.Quantile(0.95)),
                 static_cast<unsigned long long>(h.Quantile(0.99)),
                 static_cast<unsigned long long>(h.max.load(std::memory_order_relaxed)),
                 comma ? "," : "");
}

