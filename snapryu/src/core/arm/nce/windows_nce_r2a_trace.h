// Where the target core's host code last said it was. Guest execution has no marker of its own:
// a refusal while the marker reads Transition means the entry tail or the exit head.
enum class Phase : u8 {
    Idle = 0,         // outside RunThread
    EntryPrepare = 1, // RunThread loop: reason check, stack lease, TEB bounds (Covered candidate H1)
    Transition = 2,   // entry tail, guest code, or exit head
    HostReturn = 3,   // RunThread after the native call returned
    Fallback = 4,     // RunThread x18 fallback / write-step / fault emulation (candidate H3)
    DirectX18 = 5,    // generated-code direct x18 helper (candidate H2)
    Retire = 6,       // RunThread epilogue
    Count = 7,
};

enum class Reject : u8 {
    PBusyPrecheck = 0, // worker saw the parameter lock held and did not suspend
    HostStack = 1,     // captured SP on the host stack
    PatchWindow = 2,   // captured PC inside generated patch code
    HostPc = 3,        // captured PC outside the guest address space
    PBusyAtGuest = 4,  // guest PC, but the parameter lock was held
    SetFailed = 5,
    Count = 6,
};

enum class End : u8 {
    Delivered = 0,
    Retired = 1, // RunThread retired first; esr_el1 carries the request into the next entry
    ResumeFailed = 2,
    SuspendOrGetFailed = 3,
    HostSide = 4, // R2b-B3: RunThread was in host code that reads esr_el1 before guest code
    SetFailedSticky = 5, // R2b-S12: SetThreadContext failed three times in a row
    Count = 6,
};

// R2b-B2: why a patch-window capture was not recovered. It is then retried exactly as before.
enum class RecoveryFail : u8 {
    NoRecipe = 0,       // no sealed x18 substitution recipe covers the PC
    RecipeShape = 1,    // recorded offsets differ from this binary's layout
    CodeMismatch = 2,   // generated bytes differ from the recipe
    TebMismatch = 3,    // captured physical x18 is not the bound thread's TEB
    ParamsMismatch = 4, // TEB params slot or native_context is not this epoch's
    PBusy = 5,          // parameter lock held
    SetFailed = 6,      // SetThreadContext failed; given back before resume
    ReadFailed = 7,     // R2b-B2r1: code words or a TEB slot could not be read
    Count = 8,
};

inline constexpr std::size_t RecoverySteps = 15;

